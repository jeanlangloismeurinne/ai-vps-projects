-- Migration 065 — LE RANGEMENT EN BASE DE LA LECTURE (module M3 « connaissance ») ET DU DÉCLENCHEUR
-- (module « etude »). Dossier d'ouverture : `roadmap/V3/M3-base-connaissance.md` (K5, K10 « base »).
-- Contrats : `app/modules/connaissance/contrat.py`, `app/modules/etude/contrat.py`.
--
-- ADDITIVE : cinq tables NEUVES, aucune donnée existante touchée. Réversible par `DROP TABLE`.
-- DÉPEND DE 064 : une lecture nomme le document de la collecte dont elle vient (clé étrangère).
--
-- ORDRE DU CHANTIER : les deux contrats (les Protocols `Depot`, prouvés en mémoire par
-- `checks/check_connaissance.py` et `checks/check_etude.py`) sont écrits AVANT ; ces colonnes et ces
-- CHECK en sont la projection. Éprouvée sur une base jetable (`checks/check_connaissance_persist.py`) ;
-- PAS ENCORE APPLIQUÉE en production.
--
-- CE QUE FERAIT UN VRAI FONDS
--   La documentation met un document en lecture une fois pour toutes (lignes numérotées) : une
--   lecture ne se réécrit pas, un lecteur amélioré en produit une autre à côté. Une pièce citée au
--   dossier ne se retouche jamais. Le registre des titres mis à l'étude (par qui, quand, pourquoi) et
--   le journal de ce que l'analyste a fait à chaque passage sont des pistes d'audit : on n'y efface
--   rien. Tout est en AJOUT SEUL ; il n'y a aucun ÉTAT ici (celui du dossier vit dans `chef_etats`,
--   migration 063). Le verrou « un passage tient ce dossier » n'est pas une table : c'est un verrou
--   consultatif de session (`pg_try_advisory_lock`), relâché par la base si le passage meurt.
--
-- PROPRIÉTÉ (charte des modules, point 1) : `connaissance_*` n'est lu que par
-- `app/modules/connaissance/`, `etude_*` que par `app/modules/etude/` — gardé par
-- `checks/check_charte_modules.py` [C6] (préfixes déclarés au registre des modules).

BEGIN;

-- ── Les lectures (une ligne par document et version du lecteur, AJOUT SEUL) ─────────────────
-- `rang` = ordre de mise en lecture (celui du dépôt en mémoire) : `now()` est le même pour toute une
-- transaction, il n'ordonne rien.
CREATE TABLE public.connaissance_lectures (
    empreinte     text        NOT NULL REFERENCES public.recueil_documents (empreinte),
    lecteur       text        NOT NULL,
    rang          integer     GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    emetteur      text        NOT NULL,
    fiche         jsonb       NOT NULL,
    enregistre_le timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (empreinte, lecteur),

    CONSTRAINT connaissance_lectures_texte CHECK (btrim(lecteur) <> '' AND btrim(emetteur) <> ''),
    CONSTRAINT connaissance_lectures_statut CHECK (fiche ->> 'statut' IN ('lue', 'impossible', 'sans_objet')),
    CONSTRAINT connaissance_lectures_coherence CHECK (
        fiche ->> 'empreinte' = empreinte AND fiche ->> 'lecteur' = lecteur
        AND fiche ->> 'emetteur' = emetteur)
);

CREATE INDEX idx_connaissance_lectures_emetteur ON public.connaissance_lectures (emetteur, rang);

-- ── Les lignes d'une lecture (séparées : lister les lectures ne charge pas un 10-K entier) ───
-- `text[]` : une ligne ne contient jamais de saut de ligne, mais rien ne repose sur cette propriété.
CREATE TABLE public.connaissance_lignes (
    empreinte     text        NOT NULL,
    lecteur       text        NOT NULL,
    lignes        text[]      NOT NULL,
    PRIMARY KEY (empreinte, lecteur),
    FOREIGN KEY (empreinte, lecteur) REFERENCES public.connaissance_lectures (empreinte, lecteur)
);

-- ── Les pièces (une ligne par identifiant, AJOUT SEUL) ──────────────────────────────────────
-- L'identifiant est l'empreinte de (document, lecture, lignes, extrait, période) : la même pièce
-- citée deux fois n'est rangée qu'une fois. Une pièce nomme la lecture d'où elle vient.
CREATE TABLE public.connaissance_pieces (
    identifiant   text        PRIMARY KEY,
    rang          integer     GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    emetteur      text        NOT NULL,
    empreinte     text        NOT NULL,
    lecteur       text        NOT NULL,
    contenu       jsonb       NOT NULL,
    enregistre_le timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (empreinte, lecteur) REFERENCES public.connaissance_lectures (empreinte, lecteur),

    CONSTRAINT connaissance_pieces_texte CHECK (btrim(identifiant) <> '' AND btrim(emetteur) <> ''
                                                AND btrim(contenu ->> 'extrait') <> ''
                                                AND btrim(contenu ->> 'auteur') <> ''),
    CONSTRAINT connaissance_pieces_lignes CHECK (
        (contenu ->> 'ligne_debut')::int >= 1
        AND (contenu ->> 'ligne_fin')::int >= (contenu ->> 'ligne_debut')::int),
    CONSTRAINT connaissance_pieces_coherence CHECK (
        contenu ->> 'identifiant' = identifiant AND contenu ->> 'emetteur' = emetteur
        AND contenu ->> 'empreinte' = empreinte AND contenu ->> 'lecteur' = lecteur)
);

CREATE INDEX idx_connaissance_pieces_emetteur ON public.connaissance_pieces (emetteur, rang);

-- ── Les sociétés mises à l'étude (une ligne par dossier, AJOUT SEUL) ────────────────────────
CREATE TABLE public.etude_etudes (
    dossier       text        PRIMARY KEY,
    contenu       jsonb       NOT NULL,
    enregistre_le timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT etude_etudes_texte CHECK (btrim(dossier) <> '' AND btrim(contenu ->> 'par') <> ''
                                         AND btrim(contenu ->> 'motif') <> ''),
    CONSTRAINT etude_etudes_coherence CHECK (contenu ->> 'dossier' = dossier)
);

-- ── Le journal des passages (une ligne par passage qui a fait quelque chose, AJOUT SEUL) ────
CREATE TABLE public.etude_passages (
    rang          integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dossier       text        NOT NULL REFERENCES public.etude_etudes (dossier),
    contenu       jsonb       NOT NULL,
    enregistre_le timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT etude_passages_coherence CHECK (contenu ->> 'dossier' = dossier)
);

CREATE INDEX idx_etude_passages_dossier ON public.etude_passages (dossier, rang);

-- ── Ajout seul (motif de 051/061/062/063/064) ───────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.connaissance_etude_registre_immuable() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION '% est un registre : une ligne ne se modifie ni ne se supprime, '
                  'une correction s''AJOUTE (migration 065)', TG_TABLE_NAME;
END $$;

CREATE TRIGGER connaissance_lectures_immuable
    BEFORE UPDATE OR DELETE ON public.connaissance_lectures
    FOR EACH ROW EXECUTE FUNCTION public.connaissance_etude_registre_immuable();

CREATE TRIGGER connaissance_lignes_immuable
    BEFORE UPDATE OR DELETE ON public.connaissance_lignes
    FOR EACH ROW EXECUTE FUNCTION public.connaissance_etude_registre_immuable();

CREATE TRIGGER connaissance_pieces_immuable
    BEFORE UPDATE OR DELETE ON public.connaissance_pieces
    FOR EACH ROW EXECUTE FUNCTION public.connaissance_etude_registre_immuable();

CREATE TRIGGER etude_etudes_immuable
    BEFORE UPDATE OR DELETE ON public.etude_etudes
    FOR EACH ROW EXECUTE FUNCTION public.connaissance_etude_registre_immuable();

CREATE TRIGGER etude_passages_immuable
    BEFORE UPDATE OR DELETE ON public.etude_passages
    FOR EACH ROW EXECUTE FUNCTION public.connaissance_etude_registre_immuable();

-- Les privilèges par défaut (#15) donneraient TOUT au rôle applicatif : il lit et ajoute, rien d'autre.
REVOKE ALL ON public.connaissance_lectures, public.connaissance_lignes, public.connaissance_pieces,
             public.etude_etudes, public.etude_passages FROM portfolio_user;
GRANT SELECT, INSERT ON public.connaissance_lectures, public.connaissance_lignes, public.connaissance_pieces,
                       public.etude_etudes, public.etude_passages TO portfolio_user;

-- ── 065/K1 : le rôle applicatif ne peut réécrire ni supprimer aucun des cinq registres ───────
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['public.connaissance_lectures', 'public.connaissance_lignes',
                           'public.connaissance_pieces', 'public.etude_etudes', 'public.etude_passages'] LOOP
    IF has_table_privilege('portfolio_user', t, 'UPDATE')
       OR has_table_privilege('portfolio_user', t, 'DELETE')
       OR has_table_privilege('portfolio_user', t, 'TRUNCATE') THEN
      RAISE EXCEPTION '065/K1 : le rôle applicatif peut réécrire % — un registre réécrivable n''est '
                      'pas une piste d''audit', t;
    END IF;
    IF NOT has_table_privilege('portfolio_user', t, 'INSERT') THEN
      RAISE EXCEPTION '065/K1 : le rôle applicatif ne peut pas inscrire dans %', t;
    END IF;
  END LOOP;
END $$;

COMMENT ON TABLE public.connaissance_lectures IS
    'Lectures des documents collectés (migration 065, module connaissance) : une ligne par document et '
    'version du lecteur, ajout seul. Lue par `app/modules/connaissance/` uniquement.';
COMMENT ON TABLE public.connaissance_lignes IS
    'Lignes numérotées d''une lecture (migration 065) : séparées pour qu''un écran qui liste les '
    'lectures ne charge pas leur texte. Ajout seul.';
COMMENT ON TABLE public.connaissance_pieces IS
    'Pièces : extraits vérifiés mot pour mot d''une lecture (migration 065). Ajout seul ; ce que vaut '
    'leur source n''est pas rangé ici, il se redemande au registre des sources à chaque lecture.';
COMMENT ON TABLE public.etude_etudes IS
    'Sociétés mises à l''étude (migration 065, module etude) : par qui, quand, pourquoi. Ajout seul.';
COMMENT ON TABLE public.etude_passages IS
    'Journal des passages de la tâche de fond qui ont fait quelque chose (migration 065). Ajout seul.';

COMMIT;
