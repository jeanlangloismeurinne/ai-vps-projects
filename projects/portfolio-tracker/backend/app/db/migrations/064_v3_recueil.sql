-- Migration 064 — LE RANGEMENT EN BASE DE LA COLLECTE (module M2 « recueil »)
-- (reconstruction ; plan `roadmap/V3/07-avant-comite.md`, dossier d'ouverture
-- `roadmap/V3/M2-collecte-sources.md`). Contrat : `app/modules/recueil/contrat.py`.
--
-- ADDITIVE : cinq tables NEUVES, aucune donnée existante touchée. Réversible par `DROP TABLE`.
--
-- ORDRE DU CHANTIER : le contrat (`app/modules/recueil/contrat.py`, le Protocol `Depot`, déjà
-- prouvé en mémoire par `checks/check_recueil.py`) est écrit AVANT ; ces colonnes et ces CHECK en
-- sont la projection. Éprouvée sur une base PostgreSQL 16 locale/jetable le 2026-11-16
-- (`checks/check_recueil_persist.py`) ; PAS ENCORE APPLIQUÉE en production.
--
-- CE QUE FERAIT UN VRAI FONDS
--   La documentation range les documents bruts qu'elle collecte : une fois rangé, un document ne
--   se réécrit pas (deux registres : sa fiche et son contenu, séparés pour qu'un écran qui liste
--   les documents n'ait jamais à charger un PDF de 12 Mo). Elle tient aussi le registre de ses
--   réponses (une par demande, la dernière fait foi) — également en AJOUT SEUL, comme les deux
--   registres de la fiche (migration 063, même motif : 051/061/062). Le travail en cours (une
--   demande lancée, répondue ou en échec) et les sources inconnues rencontrées, eux, sont un ÉTAT :
--   ils avancent, et se réécrivent.
--
-- PROPRIÉTÉ (charte des modules, point 1) : `recueil_*` n'est lu que par `app/modules/recueil/`
-- — gardé par `checks/check_charte_modules.py` [C6] (préfixe déclaré au registre des modules).

BEGIN;

-- ── Les documents rangés (une ligne par empreinte, AJOUT SEUL) ──────────────────────────────
-- `adaptateur`, `identifiant` et `partie` sont extraits de `fiche_document["provenance"]` pour
-- servir `parties_rangees` (la collecte lit « ce qui est déjà rangé pour CE dépôt » avant de
-- retélécharger) sans avoir à désérialiser la fiche entière à chaque appel.
CREATE TABLE public.recueil_documents (
    empreinte     text        PRIMARY KEY,
    emetteur      text        NOT NULL,
    adaptateur    text        NOT NULL,
    identifiant   text        NOT NULL DEFAULT '',
    partie        text        NOT NULL DEFAULT '',
    fiche         jsonb       NOT NULL,
    enregistre_le timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT recueil_documents_texte CHECK (btrim(empreinte) <> '' AND btrim(emetteur) <> ''
                                              AND btrim(adaptateur) <> ''),
    CONSTRAINT recueil_documents_provenance CHECK (jsonb_typeof(fiche -> 'provenance') = 'object'),
    -- La ligne et sa fiche disent la même chose : ni document rangé sous un autre émetteur, ni
    -- colonnes extraites qui divergent de la provenance qu'elles résument.
    CONSTRAINT recueil_documents_coherence CHECK (
        fiche ->> 'empreinte' = empreinte
        AND fiche ->> 'emetteur' = emetteur
        AND fiche -> 'provenance' ->> 'adaptateur' = adaptateur
        AND coalesce(fiche -> 'provenance' ->> 'identifiant', '') = identifiant
        AND coalesce(fiche -> 'provenance' ->> 'partie', '') = partie)
);

CREATE INDEX idx_recueil_documents_parties
    ON public.recueil_documents (emetteur, adaptateur, identifiant) WHERE identifiant <> '';

-- ── Le contenu brut (séparé : lister les documents ne charge pas leurs octets) ──────────────
CREATE TABLE public.recueil_contenus (
    empreinte     text        PRIMARY KEY REFERENCES public.recueil_documents (empreinte),
    contenu       bytea       NOT NULL,
    enregistre_le timestamptz NOT NULL DEFAULT now()
);

-- ── Les réponses (une ligne par ajout — `rang` = ordre d'ajout, AJOUT SEUL) ──────────────────
-- La dernière réponse à chaque demande fait foi (`contrat.lire_recueil`) : le lecteur relit dans
-- l'ordre de `rang` et garde la dernière par clé de demande, jamais l'inverse.
CREATE TABLE public.recueil_reponses (
    rang          integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emetteur      text        NOT NULL,
    contenu       jsonb       NOT NULL,
    enregistre_le timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT recueil_reponses_texte CHECK (btrim(emetteur) <> ''),
    CONSTRAINT recueil_reponses_documents CHECK (jsonb_typeof(contenu -> 'documents') = 'array'),
    CONSTRAINT recueil_reponses_coherence CHECK (contenu -> 'demande' ->> 'emetteur' = emetteur)
);

CREATE INDEX idx_recueil_reponses_emetteur ON public.recueil_reponses (emetteur, rang);

-- ── Le travail en cours (une ligne par demande lancée — ÉTAT, modifiable) ────────────────────
-- `ecrire_travail` REMPLACE la ligne de sa clé : une demande relancée après un échec, ou dont la
-- fiche vient d'être corrigée, se réécrit — jamais un second rang comme les deux registres
-- ci-dessus. `rang` n'ordonne que l'AFFICHAGE (ordre de PREMIÈRE écriture, comme l'ordre
-- d'insertion d'un dict Python) : un remplacement ne le touche pas.
CREATE TABLE public.recueil_travaux (
    cle           text        PRIMARY KEY,
    rang          integer     GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    emetteur      text        NOT NULL,
    contenu       jsonb       NOT NULL,
    range_le      timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT recueil_travaux_texte CHECK (btrim(cle) <> '' AND btrim(emetteur) <> ''),
    CONSTRAINT recueil_travaux_coherence CHECK (
        contenu ->> 'cle' = cle AND contenu -> 'demande' ->> 'emetteur' = emetteur)
);

CREATE INDEX idx_recueil_travaux_emetteur ON public.recueil_travaux (emetteur, rang);

-- ── Les sources inconnues rencontrées (une ligne par source — ÉTAT, modifiable) ──────────────
-- Une source déjà notée GARDE son état : `noter_source_rencontree` ne fusionne que ses adresses
-- (dédupliquées, dans l'ordre : les anciennes d'abord), jamais ses autres champs ; `marquer_source`
-- fusionne les champs qu'on lui donne sur l'état existant (le jugement de l'évaluateur, sa dépense).
-- Clé = `source` seule (pas l'émetteur) : une source rencontrée par deux dossiers n'est évaluée
-- qu'une fois (ARCHITECTURE.md), sa dépense reste déclarée au dossier qui l'a rencontrée en premier.
-- `rang` n'ordonne que l'affichage (ordre de première rencontre) ; une fusion ne le touche pas.
CREATE TABLE public.recueil_sources_rencontrees (
    source        text        PRIMARY KEY,
    rang          integer     GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    emetteur      text        NOT NULL,
    contenu       jsonb       NOT NULL,
    range_le      timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT recueil_sources_rencontrees_texte CHECK (btrim(source) <> '' AND btrim(emetteur) <> ''),
    CONSTRAINT recueil_sources_rencontrees_adresses CHECK (jsonb_typeof(contenu -> 'adresses') = 'array'),
    CONSTRAINT recueil_sources_rencontrees_coherence CHECK (
        contenu ->> 'source' = source AND contenu ->> 'emetteur' = emetteur)
);

-- ── Ajout seul (motif de 051/061/062, repris de 063) ─────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.recueil_registre_immuable() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION '% est un registre de la collecte : une ligne ne se modifie ni ne se supprime, '
                  'une correction s''AJOUTE (migration 064)', TG_TABLE_NAME;
END $$;

CREATE TRIGGER recueil_documents_immuable
    BEFORE UPDATE OR DELETE ON public.recueil_documents
    FOR EACH ROW EXECUTE FUNCTION public.recueil_registre_immuable();

CREATE TRIGGER recueil_contenus_immuable
    BEFORE UPDATE OR DELETE ON public.recueil_contenus
    FOR EACH ROW EXECUTE FUNCTION public.recueil_registre_immuable();

CREATE TRIGGER recueil_reponses_immuable
    BEFORE UPDATE OR DELETE ON public.recueil_reponses
    FOR EACH ROW EXECUTE FUNCTION public.recueil_registre_immuable();

-- Les privilèges par défaut (#15) donneraient TOUT au rôle applicatif : les trois registres ne
-- se réécrivent jamais depuis l'application (le trigger le refuserait de toute façon, mais le
-- privilège lui-même n'est pas donné — motif de 063) ; l'état, lui, se lit, s'ajoute et se
-- réécrit, mais ne se supprime pas.
REVOKE ALL ON public.recueil_documents, public.recueil_contenus, public.recueil_reponses,
             public.recueil_travaux, public.recueil_sources_rencontrees FROM portfolio_user;
GRANT SELECT, INSERT ON public.recueil_documents, public.recueil_contenus, public.recueil_reponses
    TO portfolio_user;
GRANT SELECT, INSERT, UPDATE ON public.recueil_travaux, public.recueil_sources_rencontrees
    TO portfolio_user;

-- ── 064/K1 : le rôle applicatif ne peut réécrire ni supprimer les trois registres ; il ne peut
-- pas supprimer l'état ──────────────────────────────────────────────────────────────────────
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['public.recueil_documents', 'public.recueil_contenus', 'public.recueil_reponses'] LOOP
    IF has_table_privilege('portfolio_user', t, 'UPDATE')
       OR has_table_privilege('portfolio_user', t, 'DELETE')
       OR has_table_privilege('portfolio_user', t, 'TRUNCATE') THEN
      RAISE EXCEPTION '064/K1 : le rôle applicatif peut réécrire % — un registre réécrivable n''est '
                      'pas une piste d''audit', t;
    END IF;
    IF NOT has_table_privilege('portfolio_user', t, 'INSERT') THEN
      RAISE EXCEPTION '064/K1 : le rôle applicatif ne peut pas inscrire dans %', t;
    END IF;
  END LOOP;
  FOREACH t IN ARRAY ARRAY['public.recueil_travaux', 'public.recueil_sources_rencontrees'] LOOP
    IF has_table_privilege('portfolio_user', t, 'DELETE') THEN
      RAISE EXCEPTION '064/K1 : le rôle applicatif peut supprimer l''état (%)', t;
    END IF;
    IF NOT (has_table_privilege('portfolio_user', t, 'INSERT')
            AND has_table_privilege('portfolio_user', t, 'UPDATE')) THEN
      RAISE EXCEPTION '064/K1 : le rôle applicatif ne peut pas tenir à jour l''état (%)', t;
    END IF;
  END LOOP;
END $$;

COMMENT ON TABLE public.recueil_documents IS
    'Documents rangés par la collecte (migration 064, module recueil) : une ligne par empreinte, '
    'ajout seul. Lue par `app/modules/recueil/` uniquement ; le reste passe par `contrat.lire_recueil`.';
COMMENT ON TABLE public.recueil_contenus IS
    'Contenu brut des documents rangés (migration 064) : séparé de `recueil_documents` pour qu''un '
    'écran qui liste les documents ne charge jamais leurs octets. Ajout seul.';
COMMENT ON TABLE public.recueil_reponses IS
    'Réponses à chaque demande de collecte (migration 064) : une ligne par ajout (`rang`), ajout '
    'seul ; la dernière réponse à une demande fait foi (`contrat.lire_recueil`).';
COMMENT ON TABLE public.recueil_travaux IS
    'Travail de collecte en cours (migration 064) : une ligne par demande lancée, réécrite à '
    'chaque avancée (`ecrire_travail` remplace) ; ne se supprime pas.';
COMMENT ON TABLE public.recueil_sources_rencontrees IS
    'Sources inconnues rencontrées en collectant (migration 064) : une ligne par source, réécrite '
    'à chaque notification (`noter_source_rencontree` fusionne les adresses, `marquer_source` '
    'fusionne les champs) ; ne se supprime pas.';

COMMIT;
