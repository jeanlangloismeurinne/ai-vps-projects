-- Migration 062 — LE PROCÈS-VERBAL DE L'ARCHITECTURE (chantier v3, lot M3, roadmap V3
-- `12-lot-M3-architecte.md` §6.1, conventions #84/#98/#140).
--
-- ADDITIVE : une table NEUVE (`architectures_modele_decisions`), aucune donnée existante touchée.
-- Réversible par `DROP TABLE`.
--
-- ORDRE DU CHANTIER — comme 051/061 : le contrat (`contracts/architecture_signature_schema.py`) et
-- le module `modele_entreprise/signature.py` (seul à écrire ici) sont écrits AVANT cette migration ;
-- ces colonnes et ces CHECK en sont la PROJECTION. Éprouvée en négatif AVANT application par
-- `checks/negatif_062.sh` (motif de `negatif_061.sh`). ÉCRITE, NON APPLIQUÉE par cette session (§0 de
-- la spec M3 : Opus vérifie d'abord) — ne jamais l'appliquer ici.
--
-- CE QUE FERAIT UN VRAI FONDS
--   Le directeur de la recherche SIGNE l'architecture que l'analyste (l'agent architecte) propose, ou
--   l'ÉCARTE, motif écrit — et le PV garde les ÉCARTS NOMMÉS ([S2]/[S3b]) qu'il avait sous les yeux en
--   décidant : six mois plus tard, on doit pouvoir relire ce que le comité savait. Rien ne se réécrit :
--   une révision est une version NOUVELLE d'architecture (061), une décision nouvelle s'AJOUTE ici.
--   Une version se décide UNE fois (`architecture_id` UNIQUE) — jamais deux fois, jamais signée ET
--   écartée. ⟹ un registre APPEND-ONLY de plus (le rôle applicatif n'a ni UPDATE ni DELETE, un trigger
--   refuse même au propriétaire, copié du motif de 051/061).

BEGIN;

CREATE TABLE public.architectures_modele_decisions (
    id              integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    architecture_id integer     NOT NULL REFERENCES public.architectures_modele(id),
    action          text        NOT NULL,
    auteur          text        NOT NULL,
    motif           text        NOT NULL,
    -- Les écarts NOMMÉS ([S2]/[S3b]) que le comité avait sous les yeux en décidant — un tableau de
    -- textes, jamais vide : même une décision sans aucun écart le dit (`[]`), elle ne tait rien.
    signaux         jsonb       NOT NULL,
    decide_le       timestamptz NOT NULL DEFAULT now(),

    -- Une version se décide UNE fois : signée ou écartée, jamais les deux, jamais deux fois.
    CONSTRAINT architectures_modele_decisions_unique UNIQUE (architecture_id),
    CONSTRAINT architectures_modele_decisions_action CHECK (action IN ('signer', 'ecarter')),
    CONSTRAINT architectures_modele_decisions_texte CHECK (btrim(auteur) <> '' AND btrim(motif) <> ''),
    CONSTRAINT architectures_modele_decisions_signaux CHECK (jsonb_typeof(signaux) = 'array')
);

CREATE INDEX idx_architectures_modele_decisions_architecture
    ON public.architectures_modele_decisions (architecture_id);

-- ── Append-only (copié du motif de 051/061) ──────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.architectures_modele_decisions_immuable() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION '% est le procès-verbal de l''architecture : une décision ne se modifie ni ne se '
                  'supprime, une révision s''AJOUTE (migration 062)', TG_TABLE_NAME;
END $$;

CREATE TRIGGER architectures_modele_decisions_immuable
    BEFORE UPDATE OR DELETE ON public.architectures_modele_decisions
    FOR EACH ROW EXECUTE FUNCTION public.architectures_modele_decisions_immuable();

-- Les privilèges par défaut (#15) donneraient TOUT au rôle applicatif : on retire la réécriture.
REVOKE ALL ON public.architectures_modele_decisions FROM portfolio_user;
GRANT SELECT, INSERT ON public.architectures_modele_decisions TO portfolio_user;

-- ── 062/K1 : le rôle applicatif ne peut QUE lire et ajouter ──────────────────────────────────────
DO $$
BEGIN
  IF has_table_privilege('portfolio_user', 'public.architectures_modele_decisions', 'UPDATE')
     OR has_table_privilege('portfolio_user', 'public.architectures_modele_decisions', 'DELETE')
     OR has_table_privilege('portfolio_user', 'public.architectures_modele_decisions', 'TRUNCATE') THEN
    RAISE EXCEPTION '062/K1 : le rôle applicatif peut réécrire architectures_modele_decisions — un '
                    'registre réécrivable n''est pas une piste d''audit (A7)';
  END IF;
  IF NOT has_table_privilege('portfolio_user', 'public.architectures_modele_decisions', 'INSERT') THEN
    RAISE EXCEPTION '062/K1 : le rôle applicatif ne peut pas inscrire dans architectures_modele_decisions';
  END IF;
END $$;

COMMENT ON TABLE public.architectures_modele_decisions IS
    'Procès-verbal de signature de l''architecture du classeur (migration 062) : une décision '
    'signer/ecarter par version d''architecture (061), append-only, les signaux [S2]/[S3b] au PV. '
    'L''état de l''architecture se recalcule à la lecture (`modele_entreprise/signature.py`).';

COMMIT;
