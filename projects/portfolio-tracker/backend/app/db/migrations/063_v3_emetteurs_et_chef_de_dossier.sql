-- Migration 063 — LA FICHE DE L'ÉMETTEUR, LE JOURNAL DES SOURCES, L'ÉTAT D'UN DOSSIER
-- (reconstruction, modules M1 et M0 ; plan `roadmap/V3/07-avant-comite.md`, dossier d'ouverture
-- `roadmap/V3/M1-fiche-emetteur.md`).
--
-- ADDITIVE : trois tables NEUVES, aucune donnée existante touchée. Réversible par `DROP TABLE`.
--
-- ORDRE DU CHANTIER : les contrats (`app/modules/emetteurs/contrat.py`,
-- `app/modules/chef_de_dossier/contrat.py`) sont écrits AVANT ; ces colonnes et ces CHECK en sont
-- la projection. Éprouvée sur une base PostgreSQL 16 locale le 2026-11-13
-- (`checks/check_emetteurs_persist.py`) ; PAS ENCORE APPLIQUÉE en production.
--
-- CE QUE FERAIT UN VRAI FONDS
--   La direction de la recherche tient une fiche par société et la liste des sources admises.
--   Une fiche se corrige par une révision datée et signée ; une source se retire par un acte
--   motivé. Rien ne se réécrit : les deux registres sont en AJOUT SEUL (le rôle applicatif n'a ni
--   UPDATE ni DELETE, un trigger refuse même au propriétaire — motif de 051/061/062).
--   L'état d'un dossier, lui, est une position qui avance : il se réécrit, mais jamais deux fois
--   depuis la même lecture (colonne `revision`), et il porte son propre journal.
--
-- PROPRIÉTÉ (charte des modules, point 1) : `emetteurs_*` n'est lu que par `app/modules/emetteurs/`,
-- `chef_*` que par `app/modules/chef_de_dossier/` — gardé par `checks/check_charte_modules.py` [C6].

BEGIN;

-- ── M1 : les fiches (une ligne par révision) ─────────────────────────────────────────────────
CREATE TABLE public.emetteurs_fiches (
    id            integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emetteur      text        NOT NULL,
    revision      integer     NOT NULL,
    contenu       jsonb       NOT NULL,
    enregistre_le timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT emetteurs_fiches_unique UNIQUE (emetteur, revision),
    CONSTRAINT emetteurs_fiches_revision CHECK (revision >= 1),
    -- La ligne et son contenu disent la même chose : ni fiche rangée sous un autre nom, ni
    -- révision renumérotée.
    CONSTRAINT emetteurs_fiches_coherence CHECK (
        contenu->>'emetteur' = emetteur AND (contenu->>'revision')::integer = revision),
    -- Une révision se signe, se motive et se date.
    CONSTRAINT emetteurs_fiches_signee CHECK (
        btrim(coalesce(contenu->>'auteur', '')) <> ''
        AND btrim(coalesce(contenu->>'motif', '')) <> ''
        AND btrim(coalesce(contenu->>'le', '')) <> ''
        AND btrim(coalesce(contenu->>'raison_sociale', '')) <> ''
        AND btrim(coalesce(contenu->>'version_contrat', '')) <> '')
);

-- ── M1 : le journal des sources (une ligne par acte) ─────────────────────────────────────────
CREATE TABLE public.emetteurs_sources_actes (
    rang          integer     PRIMARY KEY,
    acte          text        NOT NULL,
    source        text        NOT NULL,
    portee        text        NOT NULL,
    natures       jsonb       NOT NULL,
    niveau        text        NOT NULL,
    critere       text        NOT NULL,
    auteur        text        NOT NULL,
    motif         text        NOT NULL,
    le            date        NOT NULL,
    enregistre_le timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT emetteurs_sources_actes_rang CHECK (rang >= 1),
    CONSTRAINT emetteurs_sources_actes_acte CHECK (acte IN ('admettre', 'revoquer')),
    CONSTRAINT emetteurs_sources_actes_texte CHECK (
        btrim(source) <> '' AND btrim(portee) <> '' AND btrim(auteur) <> '' AND btrim(motif) <> ''),
    CONSTRAINT emetteurs_sources_actes_natures CHECK (jsonb_typeof(natures) = 'array'),
    -- Une admission nomme ses natures et son niveau ; une révocation n'en porte aucun.
    CONSTRAINT emetteurs_sources_actes_forme CHECK (
        (acte = 'admettre' AND jsonb_array_length(natures) >= 1 AND btrim(niveau) <> '')
        OR (acte = 'revoquer' AND jsonb_array_length(natures) = 0 AND niveau = '' AND critere = '')),
    -- Une admission du système cite le critère écrit qu'elle applique.
    CONSTRAINT emetteurs_sources_actes_critere CHECK (
        NOT (acte = 'admettre' AND auteur LIKE 'systeme:%' AND btrim(critere) = ''))
);

CREATE INDEX idx_emetteurs_sources_actes_source ON public.emetteurs_sources_actes (source, portee);

-- ── Ajout seul (motif de 051/061/062) ────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.emetteurs_registre_immuable() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION '% est un registre de la recherche : une ligne ne se modifie ni ne se supprime, '
                  'une correction s''AJOUTE (migration 063)', TG_TABLE_NAME;
END $$;

CREATE TRIGGER emetteurs_fiches_immuable
    BEFORE UPDATE OR DELETE ON public.emetteurs_fiches
    FOR EACH ROW EXECUTE FUNCTION public.emetteurs_registre_immuable();

CREATE TRIGGER emetteurs_sources_actes_immuable
    BEFORE UPDATE OR DELETE ON public.emetteurs_sources_actes
    FOR EACH ROW EXECUTE FUNCTION public.emetteurs_registre_immuable();

-- ── M0 : l'état d'un dossier (une ligne par dossier) ─────────────────────────────────────────
CREATE TABLE public.chef_etats (
    dossier   text        PRIMARY KEY,
    etat      jsonb       NOT NULL,
    revision  integer     NOT NULL,
    range_le  timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT chef_etats_revision CHECK (revision >= 1),
    CONSTRAINT chef_etats_coherence CHECK (
        etat->>'dossier' = dossier AND btrim(coalesce(etat->>'version_contrat', '')) <> '')
);

-- Les privilèges par défaut (#15) donneraient TOUT au rôle applicatif : on retire la réécriture
-- des deux registres ; l'état d'un dossier se lit, s'ajoute et se réécrit, mais ne se supprime pas.
REVOKE ALL ON public.emetteurs_fiches, public.emetteurs_sources_actes, public.chef_etats FROM portfolio_user;
GRANT SELECT, INSERT ON public.emetteurs_fiches, public.emetteurs_sources_actes TO portfolio_user;
GRANT SELECT, INSERT, UPDATE ON public.chef_etats TO portfolio_user;

-- ── 063/K1 : le rôle applicatif ne peut QUE lire et ajouter dans les deux registres ──────────
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['public.emetteurs_fiches', 'public.emetteurs_sources_actes'] LOOP
    IF has_table_privilege('portfolio_user', t, 'UPDATE')
       OR has_table_privilege('portfolio_user', t, 'DELETE')
       OR has_table_privilege('portfolio_user', t, 'TRUNCATE') THEN
      RAISE EXCEPTION '063/K1 : le rôle applicatif peut réécrire % — un registre réécrivable n''est '
                      'pas une piste d''audit', t;
    END IF;
    IF NOT has_table_privilege('portfolio_user', t, 'INSERT') THEN
      RAISE EXCEPTION '063/K1 : le rôle applicatif ne peut pas inscrire dans %', t;
    END IF;
  END LOOP;
  IF has_table_privilege('portfolio_user', 'public.chef_etats', 'DELETE') THEN
    RAISE EXCEPTION '063/K1 : le rôle applicatif peut supprimer l''état d''un dossier';
  END IF;
END $$;

COMMENT ON TABLE public.emetteurs_fiches IS
    'Fiches des émetteurs (migration 063, module M1) : une ligne par révision, ajout seul. '
    'Lue par `app/modules/emetteurs/` uniquement ; le reste passe par `contrat.lire_fiche`.';
COMMENT ON TABLE public.emetteurs_sources_actes IS
    'Journal des sources (migration 063, module M1) : admissions et révocations, datées, motivées, '
    'signées, ajout seul. L''état en vigueur se recalcule en relisant le journal dans l''ordre.';
COMMENT ON TABLE public.chef_etats IS
    'État des dossiers du chef de dossier (migration 063, module M0) : une ligne par dossier, '
    'réécrite à chaque avancée sous contrôle de `revision` (deux écritures concurrentes : la '
    'seconde est refusée).';

COMMIT;
