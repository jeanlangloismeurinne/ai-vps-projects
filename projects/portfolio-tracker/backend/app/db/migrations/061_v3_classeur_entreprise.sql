-- Migration 061 — LE CLASSEUR DE L'ENTREPRISE : architecture, fourchettes, scénarios, déplacements
-- (chantier v3, roadmap 09 §9/§12, lot M1, conventions #97/#98/#140).
--
-- ADDITIVE : quatre tables NEUVES, aucune donnée existante touchée. Réversible par `DROP TABLE`.
--
-- ORDRE DU CHANTIER — comme 051 : le contrat (`contracts/modele_entreprise_schema.py`), le pont
-- (`modele_entreprise/referentiel.py`) et le module d'écriture (`modele_entreprise/registre.py`)
-- sont écrits AVANT cette migration ; ces colonnes et ces CHECK en sont la PROJECTION. Éprouvée en
-- négatif AVANT application par `checks/negatif_061.sh`. NON APPLIQUÉE par cette session (§0 de la
-- spec M1 : Opus vérifie d'abord) — ne jamais l'appliquer ici.
--
-- CE QUE FERAIT UN VRAI FONDS
--   Le directeur de la recherche signe l'ARCHITECTURE que l'analyste propose (M3) ; les fourchettes
--   et les scénarios du classeur sont des registres à part, rattachés à CETTE version — une révision
--   est une ligne NOUVELLE, jamais une réécriture. Le scénario CENTRAL n'est jamais une ligne : c'est
--   l'absence de déplacement (contrat `SCENARIO_CENTRAL`), sinon il pourrait diverger de sa
--   définition. ⟹ quatre registres APPEND-ONLY (le rôle applicatif n'a ni UPDATE ni DELETE, un
--   trigger refuse même au propriétaire, copié du motif de 051).

BEGIN;

CREATE TABLE public.architectures_modele (
    id                  integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker_id           text        NOT NULL REFERENCES public.tickers(id),
    version             integer     NOT NULL,
    schema_version      text        NOT NULL,
    version_referentiel text        NOT NULL,
    auteur              text        NOT NULL,
    -- L'`Architecture` ENTIÈRE (blocs, variables propres, passage à l'agrégé, cellules attendues) :
    -- ce que le comité signera (M3), pas une projection en colonnes qui pourrait diverger du contrat.
    contenu             jsonb       NOT NULL,
    propose_le          timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT architectures_modele_unique UNIQUE (ticker_id, version),
    CONSTRAINT architectures_modele_version CHECK (version >= 1),
    CONSTRAINT architectures_modele_auteur CHECK (btrim(auteur) <> ''),
    -- La ligne et son contenu disent la même chose (comme 051) : une architecture de NVDA rangée
    -- sous RVMD, ou une v2 rangée en v3, serait signée (M3) pour ce qu'elle n'est pas.
    CONSTRAINT architectures_modele_contenu CHECK (
        jsonb_typeof(contenu) = 'object'
        AND contenu->>'ticker_id' = ticker_id
        AND contenu->>'version' = version::text
        AND contenu->>'schema_version' = schema_version
    )
);

CREATE TABLE public.modele_fourchettes (
    id              integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    architecture_id integer     NOT NULL REFERENCES public.architectures_modele(id),
    bloc            text        NOT NULL,
    variable        text        NOT NULL,
    periode_debut   text        NOT NULL,
    periode_fin     text        NOT NULL,
    bas             double precision NOT NULL,
    haut            double precision NOT NULL,
    methode         text        NOT NULL,
    -- La `Fourchette` ENTIÈRE (bornes, méthode, origines des deux bornes) — projection, pas une copie.
    contenu         jsonb       NOT NULL,
    auteur          text        NOT NULL,
    inscrite_le     timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT modele_fourchettes_ordonnee CHECK (bas <= haut),
    CONSTRAINT modele_fourchettes_auteur CHECK (btrim(auteur) <> ''),
    -- Projection du contrat `Fourchette` : la ligne et son contenu disent la même chose.
    CONSTRAINT modele_fourchettes_contenu CHECK (
        jsonb_typeof(contenu) = 'object'
        AND contenu->>'bloc' = bloc
        AND contenu->>'variable' = variable
        AND contenu->>'periode_debut' = periode_debut
        AND contenu->>'periode_fin' = periode_fin
        AND (contenu->>'bas')::double precision = bas
        AND (contenu->>'haut')::double precision = haut
        AND contenu->>'methode' = methode
    )
);

CREATE INDEX idx_modele_fourchettes_architecture ON public.modele_fourchettes (architecture_id);

CREATE TABLE public.modele_scenarios (
    id              integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    architecture_id integer     NOT NULL REFERENCES public.architectures_modele(id),
    nom             text        NOT NULL,
    nature          text        NOT NULL,
    probabilite     double precision,
    -- Le `Scenario` SANS ses déplacements : ils sont leur propre registre, `modele_deplacements`.
    contenu         jsonb       NOT NULL,
    auteur          text        NOT NULL,
    inscrit_le      timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT modele_scenarios_auteur CHECK (btrim(auteur) <> ''),
    -- Le central n'est JAMAIS une ligne (contrat §2.5, 09 §12.2) : c'est l'absence de déplacement,
    -- la constante `SCENARIO_CENTRAL`. L'écrire créerait une seconde définition du central, qui
    -- pourrait diverger de la première.
    CONSTRAINT modele_scenarios_nature CHECK (nature IN ('nomme', 'branche')),
    CONSTRAINT modele_scenarios_probabilite CHECK (
        (nature = 'branche') = (probabilite IS NOT NULL)
        AND (probabilite IS NULL OR (probabilite >= 0 AND probabilite <= 1))
    )
);

CREATE INDEX idx_modele_scenarios_architecture ON public.modele_scenarios (architecture_id);

CREATE TABLE public.modele_deplacements (
    id                  integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scenario_id         integer     NOT NULL REFERENCES public.modele_scenarios(id),
    bloc                text        NOT NULL,
    variable            text        NOT NULL,
    periode_debut       text        NOT NULL,
    periode_fin         text        NOT NULL,
    cible               text        NOT NULL,
    valeur_dite         double precision,
    motif               text        NOT NULL,
    source_entry_refs   integer[]   NOT NULL DEFAULT '{}',

    CONSTRAINT modele_deplacements_motif CHECK (btrim(motif) <> ''),
    CONSTRAINT modele_deplacements_cible CHECK (cible IN ('borne_basse', 'borne_haute', 'valeur_dite')),
    CONSTRAINT modele_deplacements_valeur_dite CHECK ((cible = 'valeur_dite') = (valeur_dite IS NOT NULL))
);

CREATE INDEX idx_modele_deplacements_scenario ON public.modele_deplacements (scenario_id);

-- ── Append-only (copié du motif de 051) ──────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.classeur_entreprise_immuable() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION '% est un registre du classeur de l''entreprise : une ligne ne se modifie ni ne se '
                  'supprime, une révision s''AJOUTE (migration 061)', TG_TABLE_NAME;
END $$;

CREATE TRIGGER architectures_modele_immuable
    BEFORE UPDATE OR DELETE ON public.architectures_modele
    FOR EACH ROW EXECUTE FUNCTION public.classeur_entreprise_immuable();
CREATE TRIGGER modele_fourchettes_immuable
    BEFORE UPDATE OR DELETE ON public.modele_fourchettes
    FOR EACH ROW EXECUTE FUNCTION public.classeur_entreprise_immuable();
CREATE TRIGGER modele_scenarios_immuable
    BEFORE UPDATE OR DELETE ON public.modele_scenarios
    FOR EACH ROW EXECUTE FUNCTION public.classeur_entreprise_immuable();
CREATE TRIGGER modele_deplacements_immuable
    BEFORE UPDATE OR DELETE ON public.modele_deplacements
    FOR EACH ROW EXECUTE FUNCTION public.classeur_entreprise_immuable();

-- Les privilèges par défaut (#15) donneraient TOUT au rôle applicatif : on retire la réécriture.
REVOKE ALL ON public.architectures_modele FROM portfolio_user;
REVOKE ALL ON public.modele_fourchettes FROM portfolio_user;
REVOKE ALL ON public.modele_scenarios FROM portfolio_user;
REVOKE ALL ON public.modele_deplacements FROM portfolio_user;
GRANT SELECT, INSERT ON public.architectures_modele TO portfolio_user;
GRANT SELECT, INSERT ON public.modele_fourchettes TO portfolio_user;
GRANT SELECT, INSERT ON public.modele_scenarios TO portfolio_user;
GRANT SELECT, INSERT ON public.modele_deplacements TO portfolio_user;

-- ── 061/K1 : le rôle applicatif ne peut QUE lire et ajouter, sur les QUATRE registres ───────────
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['public.architectures_modele', 'public.modele_fourchettes',
                            'public.modele_scenarios', 'public.modele_deplacements'] LOOP
    IF has_table_privilege('portfolio_user', t, 'UPDATE')
       OR has_table_privilege('portfolio_user', t, 'DELETE')
       OR has_table_privilege('portfolio_user', t, 'TRUNCATE') THEN
      RAISE EXCEPTION '061/K1 : le rôle applicatif peut réécrire % — un registre réécrivable n''est '
                      'pas une piste d''audit (A7)', t;
    END IF;
    IF NOT has_table_privilege('portfolio_user', t, 'INSERT') THEN
      RAISE EXCEPTION '061/K1 : le rôle applicatif ne peut pas inscrire dans %', t;
    END IF;
  END LOOP;
END $$;

COMMENT ON TABLE public.architectures_modele IS
    'Versions proposées de l''architecture du classeur d''un titre (migration 061), append-only. '
    'Écrit seulement par modele_entreprise/registre.py. Signature au PV : M3 (migration 062).';
COMMENT ON TABLE public.modele_fourchettes IS
    'Fourchettes (bas/haut) des variables du classeur (migration 061), append-only.';
COMMENT ON TABLE public.modele_scenarios IS
    'Scénarios du classeur, sans leurs déplacements (migration 061), append-only. Le scénario '
    'central n''y figure jamais : c''est la constante SCENARIO_CENTRAL.';
COMMENT ON TABLE public.modele_deplacements IS
    'Déplacements d''un scénario par rapport au central (migration 061), append-only.';

COMMIT;
